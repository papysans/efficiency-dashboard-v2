// parseReportDate 解析东方财富日期格式 "2025-12-31 00:00:00" → "2025-12-31"
func parseReportDate(s string) (string, error) {
	if len(s) < 10 {
		return "", fmt.Errorf("日期格式异常，长度不足10: %q", s)
	}
	return s[:10], nil
}
